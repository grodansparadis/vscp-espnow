//

int
vscp_espnow_send_error(uint8_t err)
{
  vscpEventEx ex;

  memset(&ex, 0, sizeof(vscpEventEx));
  ex.vscp_class = VSCP_CLASS1_ERROR;
  ex.vscp_type  = VSCP_TYPE_ERROR_ERROR;
  ex.sizeData   = 5;
  ex.data[3]    = err;
  return vscp_espnow_sendEventEx(s_broadcast_mac, &ex, 1000);
}

///////////////////////////////////////////////////////////////////////////////
// vscp_espnow_is_to_me
//

bool
vscp_espnow_is_to_me(const uint8_t *pguid)
{
  uint8_t GUID[16];
  vscp_espnow_get_node_guid(GUID);
  return (0 == memcmp(GUID, pguid, 16)) ? true : false;
}

///////////////////////////////////////////////////////////////////////////////
// vscp_espnow_get_node_guid
//

int
vscp_espnow_get_node_guid(uint8_t *pguid)
{
  esp_err_t ret;

  // Check GUID pointer
  if (NULL == pguid) {
    ESP_LOGE(TAG, "Pointer to GUID is NULL");
    return VSCP_ERROR_INVALID_POINTER;
  }

  memset(pguid, 0, 16);
  memcpy(pguid, s_guid_prefix, 8);
  ret = esp_read_mac(pguid + 8, ESP_MAC_WIFI_STA);
  if (ret != ESP_OK) {
    ESP_LOGE(TAG, "esp_efuse_mac_get_default failed to get GUID. rv=%d (%s)", ret, esp_err_to_name(ret));
  }

  pguid[14] = (g_persistent.nickname << 8) & 0xff;
  pguid[15] = g_persistent.nickname & 0xff;

  return VSCP_ERROR_SUCCESS;
}

///////////////////////////////////////////////////////////////////////////////
// vscp_espnow_getFrameBufSizeEv
//

size_t
vscp_espnow_getFrameBufSizeEv(const vscpEvent *pev)
{
  // Need event pointer
  if (NULL == pev) {
    ESP_LOGE(TAG, "Pointer to event is NULL");
    return 0;
  }

  size_t padlen = VSCP_ESPNOW_VSCP_MIN_FRAME + pev->sizeData;
  padlen        = padlen + (16 - (padlen % 16));

  return (5 + 16 + padlen); // Pre + iv + vscp + padding
}

