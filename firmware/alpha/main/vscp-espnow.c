/*
 Packages can be sent open or encrypted. If encryptet they are encrypted
 with AES-128 CBC mode.  The freme is sent as

 | 0xAA | 0x55 | ttl (1 byte) | seq (1 byte) | Packet type & encryption settings (1 byte) || AES-128 CBC encrypted data
 (event) || IV (16-byte) |

 The IV is the last 16 bytes after the encrypted data and this is a rendom value
 generated by the sender of the frame. Only present if encryption is used.

 seq is a 16-bit sequence counter that is incremented for every frame sent. It is used
 to detect if a frame is lost and to detect if a frame is a duplicate.

 esp-now max-frame size is 250 bytes. The max size for a VSCP frame is 512 bytes so a full
 level II frame must be truncated. That is 250-4-14-16 = 216 bytes is the maximum data
 size.

 Packet type & encryption settings.
 ----------------------------------
 7,6,5,4 	Packet type. Currently always one.
 3,2,1,0 	Encryption. Always one for AES-128 CBC encryption.

 Format for the VSCP frame
 -------------------------

 0 	    VSCP Level II Head MSB
 1 	    VSCP Level II Head LSB
 2 	    Timestamp microseconds MSB
 3 	    Timestamp microseconds
 4 	    Timestamp microseconds
 5 	    Timestamp microseconds LSB
 6 	    CLASS MSB
 7 	    CLASS LSB
 8 	    TYPE MSB
 9 	    TYPE LSB
 10-n 	  data ... limited to max 217 bytes
 len-2 	CRC MSB (Calculated on HEAD + CLASS + TYPE + ADDRESS + SIZE + DATA…)
 len-1 	CRC LSB

 time and guid has been left out in type 2 as they are obvious from the
 context of the frame.

 For a node that is not implementing any VSCP functionality (registers, MDF etc)
 bit 15 of the header should be set.  Note also that neader bytes 0,1,2 is used for
  a rolling index and should be updated for each frame appropriatly.
*/

